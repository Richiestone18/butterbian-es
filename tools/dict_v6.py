#!/usr/bin/env python3
"""butterbian-es v6: cumulative en->es dictionary and its application to upstream.

Unlike v5 (which extracted the dictionary only from the previous payload in
memory), v6 keeps the dictionary in a persistent file (tools/dictionary.tsv)
that accumulates version after version: phrases that reappear or move between
files stay covered even if the previous payload no longer has them.

Flow:
  1. Extract (en, es, context) pairs by aligning payload/suckless (translated)
     against the BASE commit (its English upstream), per file.
  2. Merge into dictionary.tsv: new pairs are added; the same
     (file, context, en) with a different translation is a CONFLICT and is not
     overwritten (it is reported).
  3. Apply the FULL (accumulated) dictionary to the upstream at the current
     commit of the clone (work/butterdwm-full), only where the line context
     matches, and write the output.

Usage:
  dict_v6.py [--repo R] [--payload P] [--base COMMIT] [--out O] [--dic D]
Defaults: R=work/butterdwm-full  P=payload/suckless  O=work/v6/suckless
          D=tools/dictionary.tsv  BASE=first commit of R
"""
import subprocess, re, os, difflib, json, collections, argparse

STR = re.compile(r'"(?:[^"\\]|\\.)*"')
LET = re.compile(r'[A-Za-zÁÉÍÓÚáéíóúÑñ]{2}')


def git(repo, *a):
    return subprocess.run(['git', '-C', repo, *a],
                          capture_output=True).stdout.decode('utf-8', 'replace')


def norm(l):
    return STR.sub('"S"', l).strip()


def qml_files(root):
    out = []
    for d in ('quickshell', 'quickshell-network'):
        for r, _, fs in os.walk(os.path.join(root, d)):
            out += [os.path.relpath(os.path.join(r, f), root)
                    for f in fs if f.endswith('.qml')]
    return sorted(out)


def pair_lines(bl, pl):
    """Pairs (en, es) if pl is the translated line bl; None if they do not align."""
    if norm(bl) != norm(pl):
        return None
    out = []
    for a, b in zip(STR.findall(bl), STR.findall(pl)):
        if a == b:
            continue
        if not LET.search(a):
            return None          # glyph/symbol change: false alignment
        out.append((a, b))
    return out


def extract_pairs(payload, upstream_text, rel):
    """Return {(en, context): set(es)} from one translated file vs its English."""
    b = upstream_text.splitlines()
    p = open(payload, encoding='utf-8').read().splitlines()
    sm = difflib.SequenceMatcher(None, b, p, autojunk=False)
    res = collections.defaultdict(set)
    for op, i1, i2, j1, j2 in sm.get_opcodes():
        if op != 'replace':
            continue
        sub = difflib.SequenceMatcher(
            None, [norm(x) for x in b[i1:i2]], [norm(x) for x in p[j1:j2]],
            autojunk=False)
        for op2, a1, a2, c1, c2 in sub.get_opcodes():
            if op2 != 'equal':
                continue
            for bl, pl in zip(b[i1+a1:i1+a2], p[j1+c1:j1+c2]):
                r = pair_lines(bl, pl)
                if r:
                    ctx = norm(bl)
                    for en, es in r:
                        res[(en, ctx)].add(es)
    return res


def load_dict(path):
    """dictionary.tsv -> {(file, en, context): es} and conflicts."""
    d = {}
    conf = []
    if not os.path.exists(path):
        return d, conf
    with open(path, encoding='utf-8') as f:
        for n, line in enumerate(f, 1):
            line = line.rstrip('\n')
            if not line or line.startswith('#'):
                continue
            parts = line.split('\t')
            if len(parts) != 4:
                conf.append(f'{path}:{n}: format (4 columns)')
                continue
            arch, en, es, ctx = parts
            k = (arch, en, ctx)
            if k in d and d[k] != es:
                conf.append(f'{path}:{n}: conflict with {arch} «{en}»')
            d[k] = es
    return d, conf


def save_dict(path, d):
    tmp = path + '.tmp'
    with open(tmp, 'w', encoding='utf-8') as f:
        f.write('# cumulative en->es dictionary by (file, phrase, context)\n')
        f.write('# generated by dict_v6.py: do not edit by hand; it regenerates\n')
        for (arch, en, ctx), es in sorted(d.items()):
            f.write(f'{arch}\t{en}\t{es}\t{ctx}\n')
    os.replace(tmp, path)


def apply_dict(upstream, out, dic, rel):
    """Apply the dictionary to one upstream file; return (applied, pending)."""
    src = open(upstream, encoding='utf-8').read().splitlines(keepends=True)
    out_lines = []
    applied = collections.OrderedDict()
    pending = collections.OrderedDict()
    for n, l in enumerate(src, 1):
        c = norm(l)
        hit = set()

        def rep(m):
            s = m.group(0)
            if not LET.search(s):
                return s
            k = (rel, s, c)
            if k in dic:
                hit.add(s)
                applied.setdefault((s, dic[k]), []).append(f'{rel}:{n}')
                return dic[k]
            # v5 fallback: a single translation in the whole dictionary and the
            # current context has been seen with that phrase (reformatted line)
            glob = {es for (a, en, ctx), es in dic.items() if en == s}
            gctx = {ctx for (a, en, ctx) in dic if en == s}
            if len(glob) == 1 and c in gctx:
                es = next(iter(glob))
                hit.add(s)
                applied.setdefault((s, es), []).append(f'{rel}:{n}')
                return es
            return s

        nl = STR.sub(rep, l)
        out_lines.append(nl)
        for s in STR.findall(l):
            t = s[1:-1]
            if s in hit or not LET.search(t):
                continue
            if re.fullmatch(r'[\w./:%@-]+', t) and not re.search(r'[A-Z ]', t):
                continue
            pending.setdefault(t, []).append(f'{rel}:{n}')
    os.makedirs(os.path.dirname(os.path.join(out, rel)), exist_ok=True)
    open(os.path.join(out, rel), 'w', encoding='utf-8').write(''.join(out_lines))
    return applied, pending


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--repo', default='work/butterdwm-full')
    ap.add_argument('--payload', default='payload/suckless')
    ap.add_argument('--base', default='')
    ap.add_argument('--out', default='work/v6/suckless')
    ap.add_argument('--dic', default='tools/dictionary.tsv')
    a = ap.parse_args()

    here = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))  # package root
    repo = os.path.join(here, a.repo)
    pay = os.path.join(here, a.payload)
    out = os.path.join(here, a.out)

    base = a.base or git(repo, 'rev-parse', 'HEAD').strip()
    nuevo = git(repo, 'rev-parse', 'HEAD').strip()

    # 1) extract pairs from the payload against its BASE commit
    nuevos = collections.defaultdict(set)
    for f in qml_files(pay):
        en_text = git(repo, 'show', f'{base}:suckless/{f}')
        if not en_text:
            continue
        pairs = extract_pairs(os.path.join(pay, f), en_text, f)
        for (en, ctx), eses in pairs.items():
            nuevos[(f, en, ctx)] |= eses

    # 2) merge into the accumulated dictionary
    dic, conflicts = load_dict(os.path.join(here, a.dic))
    for (f, en, ctx), eses in nuevos.items():
        if len(eses) > 1:
            conflicts.append(f'{f} «{en}»: several translations {sorted(eses)}')
            continue
        es = next(iter(eses))
        k = (f, en, ctx)
        if k in dic and dic[k] != es:
            conflicts.append(f'{f} «{en}»: translation change {dic[k]} -> {es}')
            continue
        dic[k] = es
    save_dict(os.path.join(here, a.dic), dic)
    print('accumulated dictionary:', len(dic),
          '| new pairs from this payload:', sum(len(v) for v in nuevos.values()))

    # 3) apply the full dictionary to the clone's upstream (current commit)
    applied_total = collections.OrderedDict()
    pending_total = collections.OrderedDict()
    for f in qml_files(os.path.join(repo, 'suckless')):
        ap_arch, pend_arch = apply_dict(
            os.path.join(repo, 'suckless', f), out, dic, f)
        applied_total.update(ap_arch)
        pending_total.update(pend_arch)

    print('replacements applied:', sum(len(v) for v in applied_total.values()),
          '| distinct pairs used:', len(applied_total),
          '| pending (untranslated English):', len(pending_total))
    if conflicts:
        print('CONFLICTS:')
        for c in conflicts:
            print('  -', c)
    json.dump({'applied': {f'{a} => {b}': v for (a, b), v in applied_total.items()},
               'pending': pending_total, 'conflicts': conflicts},
              open(os.path.join(os.path.dirname(out), 'v6-report.json'), 'w'),
              ensure_ascii=False, indent=1)
    print('base:', base[:12], '| new (checkout):', nuevo[:12])


if __name__ == '__main__':
    main()
